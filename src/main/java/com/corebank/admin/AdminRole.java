package com.corebank.admin;

/**
 * 관리자 역할. 관리자마다 하나만 가진다. 하나만 두는 이유: 한 계정이 "요청"과 "승인"을 함께 가지면 혼자서 4-eyes 를
 * 통과한다. 역할을 하나로 묶어 두면 요청자와 승인자가 늘 다른 계정이다.
 *
 * <p>토큰의 role claim 에 들어가고, Spring Security 권한으로는 "ROLE_TELLER" 처럼 바뀐다(SecurityConfig).
 * 조회는 역할과 상관없이 모든 관리자가 한다. 아래는 역할마다 할 수 있는 <b>변경</b>이다.
 */
public enum AdminRole {

	/** 창구: 계좌 개설·입출금·이체·해지, 거래 정정 요청. 돈을 움직이는 사람 */
	TELLER,

	/** 책임자: 거래 정정 승인·반려, 관리자 등록 승인·반려. 남이 올린 것을 확인하는 사람 */
	APPROVER,

	/** 운영: 일 마감, 이자 적립·결산, 상품 등록·중지, 로그인 잠금 해제, 관리자 등록 요청 */
	OPERATOR

}
